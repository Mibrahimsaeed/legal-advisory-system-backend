"""Turn a simple list of blocks into a PDF (reportlab) or a Word file (python-docx).

A block is a (kind, text) pair:
    title    - big document title
    meta     - small grey line under the title (date, source chat)
    heading  - section heading (e.g. a case citation)
    label    - small bold label ("Your question", "Answer")
    para     - normal text (newlines kept)
    field    - "Name: value" line; text is "Name|value"
    note     - small italic text (disclaimer)
    rule     - horizontal divider (text ignored)
"""
from __future__ import annotations

import io
from datetime import datetime
from xml.sax.saxutils import escape

BRAND = "Smart Legal Advisory System"
GREEN = (0x0F, 0x6B, 0x5C)
DISCLAIMER = (
    "This document was generated by the Smart Legal Advisory System for general information only. "
    "It is not legal advice and does not replace consultation with a qualified lawyer."
)

Block = tuple[str, str]


def build(blocks: list[Block], file_format: str) -> bytes:
    if file_format == "pdf":
        return _build_pdf(blocks)
    if file_format == "docx":
        return _build_docx(blocks)
    raise ValueError(f"Unsupported format: {file_format}")


def generated_on_line() -> str:
    return "Generated on " + datetime.now().strftime("%d %B %Y, %I:%M %p")


# ---------------------------------------------------------------- PDF
def _build_pdf(blocks: list[Block]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle
    from reportlab.lib.units import mm
    from reportlab.platypus import HRFlowable, Paragraph, SimpleDocTemplate, Spacer

    green = colors.Color(*(c / 255 for c in GREEN))
    grey = colors.Color(0.42, 0.45, 0.47)
    base = ParagraphStyle("base", fontName="Helvetica", fontSize=10.5, leading=15.5, alignment=TA_LEFT)
    styles = {
        "title": ParagraphStyle("title", parent=base, fontName="Helvetica-Bold", fontSize=18, leading=23, textColor=colors.black, spaceAfter=4),
        "meta": ParagraphStyle("meta", parent=base, fontSize=9, leading=13, textColor=grey),
        "heading": ParagraphStyle("heading", parent=base, fontName="Helvetica-Bold", fontSize=13, leading=18, textColor=green, spaceBefore=10, spaceAfter=4),
        "label": ParagraphStyle("label", parent=base, fontName="Helvetica-Bold", fontSize=9.5, leading=13, textColor=green, spaceBefore=8, spaceAfter=2),
        "para": ParagraphStyle("para", parent=base, spaceAfter=6),
        "field": ParagraphStyle("field", parent=base, spaceAfter=1),
        "note": ParagraphStyle("note", parent=base, fontName="Helvetica-Oblique", fontSize=8.5, leading=12, textColor=grey),
    }

    def text(t: str) -> str:
        return escape(t).replace("\n", "<br/>")

    def on_page(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica-Bold", 8.5)
        canvas.setFillColor(green)
        canvas.drawString(18 * mm, A4[1] - 12 * mm, BRAND)
        canvas.setFont("Helvetica", 8)
        canvas.setFillColor(grey)
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc.page}")
        canvas.restoreState()

    story = []
    for kind, value in blocks:
        if kind == "rule":
            story.append(Spacer(1, 4))
            story.append(HRFlowable(width="100%", thickness=0.6, color=colors.Color(0.85, 0.88, 0.87)))
            story.append(Spacer(1, 4))
        elif kind == "field":
            name, _, val = value.partition("|")
            story.append(Paragraph(f"<b>{escape(name)}:</b> {text(val)}", styles["field"]))
        else:
            story.append(Paragraph(text(value), styles.get(kind, styles["para"])))
            if kind == "meta":
                story.append(Spacer(1, 2))

    buf = io.BytesIO()
    doc = SimpleDocTemplate(
        buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=20 * mm, bottomMargin=18 * mm,
        title=next((v for k, v in blocks if k == "title"), BRAND), author=BRAND,
    )
    doc.build(story, onFirstPage=on_page, onLaterPages=on_page)
    return buf.getvalue()


# ---------------------------------------------------------------- Word
def _build_docx(blocks: list[Block]) -> bytes:
    from docx import Document
    from docx.enum.text import WD_BREAK
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Pt, RGBColor

    green = RGBColor(*GREEN)
    grey = RGBColor(0x6B, 0x73, 0x78)
    doc = Document()
    normal = doc.styles["Normal"]
    normal.font.name = "Calibri"
    normal.font.size = Pt(11)

    header = doc.sections[0].header.paragraphs[0]
    hr = header.add_run(BRAND)
    hr.bold = True
    hr.font.size = Pt(8.5)
    hr.font.color.rgb = green

    def add_text(p, value: str, **fmt):
        lines = value.split("\n")
        for i, line in enumerate(lines):
            run = p.add_run(line)
            for k, v in fmt.items():
                if k == "color":
                    run.font.color.rgb = v
                elif k == "size":
                    run.font.size = Pt(v)
                else:
                    setattr(run, k, v)
            if i < len(lines) - 1:
                run.add_break(WD_BREAK.LINE)

    for kind, value in blocks:
        if kind == "title":
            p = doc.add_paragraph()
            add_text(p, value, bold=True, size=18)
        elif kind == "meta":
            p = doc.add_paragraph()
            add_text(p, value, size=9, color=grey)
            p.paragraph_format.space_after = Pt(2)
        elif kind == "heading":
            p = doc.add_paragraph()
            add_text(p, value, bold=True, size=13, color=green)
            p.paragraph_format.space_before = Pt(10)
        elif kind == "label":
            p = doc.add_paragraph()
            add_text(p, value, bold=True, size=9.5, color=green)
            p.paragraph_format.space_before = Pt(8)
            p.paragraph_format.space_after = Pt(0)
        elif kind == "field":
            name, _, val = value.partition("|")
            p = doc.add_paragraph()
            r = p.add_run(f"{name}: ")
            r.bold = True
            add_text(p, val)
            p.paragraph_format.space_after = Pt(0)
        elif kind == "note":
            p = doc.add_paragraph()
            add_text(p, value, italic=True, size=8.5, color=grey)
        elif kind == "rule":
            p = doc.add_paragraph()
            pPr = p._p.get_or_add_pPr()
            border = OxmlElement("w:pBdr")
            bottom = OxmlElement("w:bottom")
            for k, v in (("w:val", "single"), ("w:sz", "4"), ("w:space", "1"), ("w:color", "D9E0DE")):
                bottom.set(qn(k), v)
            border.append(bottom)
            pPr.append(border)
        else:
            p = doc.add_paragraph()
            add_text(p, value)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
